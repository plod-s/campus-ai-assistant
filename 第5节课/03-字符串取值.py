'''
数值类型:123 45.6---整体,是不能够分开的
字符串取值:每个字符都是独立---都可以单个取出来操作
字符串[索引]
1.反向取值是从-1开始
2.正向取值是从0开始
IndexError: string index out of range
索引错误      字符串  索引   超过   范围
'''
s1 = '欢迎来到码界学习！'
# 获取第一个字符----0
print(s1[0])  # [:英文状态下
print(s1[5])  # 码
print(s1[-2])  # 习
print(s1[-4])  # 学  对于空格这一类的字符他算一个字符

