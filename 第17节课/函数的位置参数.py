# 什么情况下,才会用到传参这个知识点?----里面的数据值是随时变化,对于变化的这个值,才会进行传参
# 在这样的业务逻辑当中---需要变化的值只有一个---传递一个参数

def qu_qian(money, zhanghao):
    print('===== 中国建设银行 ATM =====')
    print(f'账号:{zhanghao}')
    print('业务:快速取款')
    print(f'金额:{money}元')  # 函数里面的代码是多变的--参数
    print('币种:人民币')
    print('请取走你的现金')
    print('---------------------------')


# 使用这个工具的时候---才会进行传参
'''
1.多个参数之间一定要用逗号隔开
2.实参(实际传递的值)的个数 一定要与你工具 形参(接受实参的工具)个数 保持一致
3.位置参数:位置应该是一一对应的关系
'''
qu_qian(20000,'wcz')

